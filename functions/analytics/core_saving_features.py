"""Sprint 3 BQ: Which core saving feature has the most saved records?

Compare records that currently exist in Firestore:
- Create Wishlist: documents in wishlists.
- Add Product Manually: products without the recommendation ID prefix.
- Save Recommended Product: products linked to a valid saved recommendation.

Recommendation saves use deterministic IDs: rec_<SHA256(userId:sourceId)>.
An unmatched rec_ product is reported as unclassified rather than manual.

Deleted records are not counted. Historical events alone are not saves.
"""

import hashlib
from datetime import datetime


FEATURES = (
    ("wishlist", "Create Wishlist"),
    ("manual_product", "Add Product Manually"),
    ("recommended_product", "Save Recommended Product"),
)


def _nonempty_string(value):
    """Return whether a value is a nonempty string."""
    return isinstance(value, str) and bool(value.strip())


def _expected_recommendation_id(user_id, source_product_id):
    """Reproduce the ID generated by save_recommended_product."""
    raw = f"{user_id}:{source_product_id}".encode("utf-8")
    return "rec_" + hashlib.sha256(raw).hexdigest()


def compute_core_saving_features(wishlists, products, events):
    """Calculate counts from (document_id, data) pairs.

    Each Firestore document is counted at most once.
    Events only identify recommendation origins; they are not counted
    as separate saved records.
    """
    wishlist_ids = {
        doc_id
        for doc_id, _ in wishlists
        if _nonempty_string(doc_id)
    }

    products_by_id = {
        doc_id: data
        for doc_id, data in products
        if _nonempty_string(doc_id)
    }

    recommended_ids = set()

    for _, event in events:
        if not isinstance(event, dict):
            continue

        if event.get("eventType") != "recommendation_shown":
            continue

        if not isinstance(event.get("savedAt"), datetime):
            continue

        user_id = event.get("userId")
        source_id = event.get("sourceProductId")
        saved_id = event.get("savedProductId")

        if not all(
            _nonempty_string(value)
            for value in (user_id, source_id, saved_id)
        ):
            continue

        expected_id = _expected_recommendation_id(user_id, source_id)

        if saved_id != expected_id:
            continue

        product = products_by_id.get(saved_id)

        if not isinstance(product, dict):
            continue

        if product.get("ownerId") != user_id:
            continue

        recommended_ids.add(saved_id)

    manual_count = sum(
        not product_id.startswith("rec_")
        for product_id in products_by_id
    )

    unclassified_count = sum(
        product_id.startswith("rec_")
        and product_id not in recommended_ids
        for product_id in products_by_id
    )

    counts = {
        "wishlist": len(wishlist_ids),
        "manual_product": manual_count,
        "recommended_product": len(recommended_ids),
    }

    highest_count = max(counts.values())

    leaders = (
        [key for key, count in counts.items() if count == highest_count]
        if highest_count > 0
        else []
    )

    if highest_count == 0:
        status = "empty"
    elif len(leaders) > 1:
        status = "tie"
    else:
        status = "leader"

    return {
        "schemaVersion": 1,
        "features": [
            {
                "id": key,
                "label": label,
                "count": counts[key],
            }
            for key, label in FEATURES
        ],
        "highestCount": highest_count,
        "leaders": leaders,
        "status": status,
        "totalCurrentProducts": len(products_by_id),
        "unclassifiedProducts": unclassified_count,
        "classificationComplete": unclassified_count == 0,
    }


def compute_from_firestore(db, params):
    """Read current Firestore documents and calculate the BQ."""
    wishlists = [
        (doc.id, doc.to_dict() or {})
        for doc in db.collection("wishlists").stream()
    ]

    products = [
        (doc.id, doc.to_dict() or {})
        for doc in db.collection("products").stream()
    ]

    events = [
        (doc.id, doc.to_dict() or {})
        for doc in db.collection("productEvents").stream()
    ]

    return compute_core_saving_features(wishlists, products, events)